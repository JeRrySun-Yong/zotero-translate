"""A figure's title does not cover the caption that follows it on its line (closure ticket 18, O1).

AutoDesign page 1: the caption of figure 1 is one source paragraph. Its first
line holds the bold title "Figure 1 AutoDesign progressively improves the
design harness and the quality of the artifacts." and then "(a) Score of the
poster generated by ...". The engine's character order puts the 40 characters
of the arXiv watermark (another layout box, drawn in its own form) between
"artifacts." and "(a)", so the caption became two paragraphs in one layout
box. Each was laid out from the top of its own box, and both boxes hold the
first line: the translated "(a) ..." text was set on top of the translated
title.
"""

import pymupdf

from tests.conftest import FIXTURES

# The caption of figure 1 in the mono PDF (PyMuPDF coordinates, y down): below
# the subfigure captions "(a) ...", "(b) ..." (y 632-644) and above the
# footnotes (y 715).
CAPTION = pymupdf.Rect(60, 648, 560, 712)
# The scorecard's "overlap" rule (tools/scorecard/scorecard.py): two glyph boxes
# overlap when they share at least 1 pt horizontally and at least 30 % of the
# shorter glyph's height vertically; a glyph box is as high as the font size.
OVERLAP_MIN_DX = 1.0
OVERLAP_SHARE = 0.3


def caption_lines(page: pymupdf.Page) -> list[tuple[str, list[pymupdf.Rect]]]:
    """(text, glyph boxes) of each text line inside ``CAPTION``."""
    small = pymupdf.TOOLS.set_small_glyph_heights()
    pymupdf.TOOLS.set_small_glyph_heights(True)
    try:
        raw = page.get_text("rawdict", clip=CAPTION)
    finally:
        pymupdf.TOOLS.set_small_glyph_heights(bool(small))
    lines = []
    for block in raw["blocks"]:
        for line in block.get("lines", []):
            chars = [ch for span in line["spans"] for ch in span["chars"] if ch["c"].strip()]
            if chars:
                lines.append(("".join(ch["c"] for ch in chars), [pymupdf.Rect(ch["bbox"]) for ch in chars]))
    return lines


def overlapping_pairs(lines: list[tuple[str, list[pymupdf.Rect]]]) -> list[tuple[str, str]]:
    pairs = []
    for i, (text_a, boxes_a) in enumerate(lines):
        for text_b, boxes_b in lines[i + 1 :]:
            if any(
                min(a.x1, b.x1) - max(a.x0, b.x0) >= OVERLAP_MIN_DX
                and min(a.y1, b.y1) - max(a.y0, b.y0) >= OVERLAP_SHARE * min(a.height, b.height) > 0
                for a in boxes_a
                for b in boxes_b
            ):
                pairs.append((text_a[:30], text_b[:30]))
    return pairs


def test_the_figure_title_and_the_subfigure_caption_do_not_overlap(fake_model, start_service, tmp_path):
    service = start_service(fake_model)
    task_id = service.submit(FIXTURES / "autodesign-p1.pdf")
    final = service.wait(task_id)
    assert final["state"] == "succeeded", final["error"]

    mono = tmp_path / "mono.pdf"
    mono.write_bytes(service.download(task_id, "mono"))
    with pymupdf.open(mono) as doc:
        lines = caption_lines(doc[0])
    text = "".join(t for t, _ in lines)
    # Both parts of the caption are on the page (pseudo translations keep the
    # source words), the title first.
    title, subfigure = text.find("Figure1AutoDesign"), text.find("(a)Scoreoftheposter")
    assert 0 <= title < subfigure, text
    assert overlapping_pairs(lines) == []
